/**
 * Ошибки со статусом 401, которые говорят не о протухшей сессии, а о том,
 * что пользователь ввёл неверные учетные данные при авторизации или смене пароля.
 *
 * Раньше любой 401 считался истёкшей сессией и выбрасывал на страницу
 * входа. Из-за этого ошибка «неверный текущий пароль» при его смене
 * выкидывала из аккаунта вместе со всеми введёнными данными: сессия была цела,
 * а пользователь оказывался на форме входа.
 */
export function isUserFacingAuthError(code: string | undefined): boolean {
  return code === 'wrong_password' || code === 'invalid_2fa' || code === 'invalid_credentials';
}
