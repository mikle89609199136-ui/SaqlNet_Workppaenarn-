/**
 * Сообщения, по которым прямо сейчас меняются реакции.
 *
 * Замена реакции — два обращения к серверу: сначала снять прежнюю, потом
 * поставить новую. Между ними на сервере существует состояние «реакции
 * нет», и он честно рассылает его всем — включая нас. Применив эту весть,
 * интерфейс на пару сотен миллисекунд показывал пустоту вместо только что
 * выбранного эмодзи.
 *
 * Пока операция не закончилась, чужие вести по этому сообщению
 * пропускаются: свой ответ придёт следом и принесёт окончательное
 * состояние. Уйдёт вместе с #566 — там замена станет одним запросом, и
 * промежуточного состояния не будет вовсе.
 *
 * Живёт вне React: меню действий размонтируется сразу после нажатия, а
 * знать о незавершённой операции нужно обработчику событий сокета.
 */
const pending = new Set<string>();

export function beginReactionChange(messageId: string): void {
  pending.add(messageId);
}

export function endReactionChange(messageId: string): void {
  pending.delete(messageId);
}

export function isReactionChangePending(messageId: string): boolean {
  return pending.has(messageId);
}
