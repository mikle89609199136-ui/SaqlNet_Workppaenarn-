/* Оформление строки списка чатов — общее для всех, кто её рисует:
   самой строки, скелетона, входа в архив и найденных людей.

   Отдельной константой, а не набором классов в каждом файле, ради
   одного правила: разделителя между соседними строками. Он записан
   вариантом `[&+&]:border-t`, а такой вариант срабатывает, только если
   у обоих соседей стоит один и тот же класс. Одинаковым он остаётся
   ровно до тех пор, пока строка собирается из одной строки текста:
   разойдись эти наборы хоть на класс — и разделители пропадут молча,
   без ошибки и без падения теста.

   Всё, что внутри строки, живёт в разметке своих компонентов: разным
   её хозяевам нужно разное.

   Ширина колонки под аватарку задана числом, а не `grid-cols-[auto_1fr]`:
   скелетон обязан совпадать со строкой по геометрии, и колонка,
   посчитанная по содержимому, развела бы их при первой же правке
   размера аватарки.

   `text-inherit` — потому что строкой бывает и ссылка, и кнопка: у
   каждой свой цвет текста от браузера. */
