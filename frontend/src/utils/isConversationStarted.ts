import type { IChatDto } from '@/types';

/**
 * Началась ли переписка.
 *
 * Личный чат заводится на сервере в тот момент, когда человека открыли из
 * поиска, — до первого сообщения это ещё не переписка, а намерение. В
 * списке чатов такие не показываются: иначе он пополнялся бы каждым, к
 * кому просто заглянули.
 *
 * Группы считаются начатыми всегда: пустая группа — это не «заглянул», а
 * созданная своими руками комната, которая иначе пропала бы сразу после
 * создания.
 *
 * Правило живёт здесь, а не в запросе списка: тем же запросом
 * пользуется выбор участников группы, и там нужны все собеседники, в том
 * числе те, кому ещё не написали.
 */
export function isConversationStarted(chat: IChatDto): boolean {
  return chat.type !== 'private' || Boolean(chat.lastMessage);
}
